/**
 * Payables document & payment detail — one read-only shape for every payable the hub lists, so the accountant
 * sees a document (vendor bill / cash approval / PO advance) and each payment made against it on the same layout.
 *
 * Document: header, info fields, lines, totals, balance, payments made, accounting entries, and which existing
 * payment window the Pay button opens (`action`, same values as the hub rows). Nothing here posts anything.
 * Payment: keyed by the payment's journal entry (voucher); finds what it paid (bills via ApPaymentApplication or
 * bill.payments, a vendor advance, or a cash approval) and returns the same kind of summary + accounting entry.
 */
const mongoose = require('mongoose');
const AccountsPayable = require('../models/finance/AccountsPayable');
const ApPaymentApplication = require('../models/finance/ApPaymentApplication');
const JournalEntry = require('../models/finance/JournalEntry');
const VendorAdvance = require('../models/finance/VendorAdvance');
const CashApproval = require('../models/procurement/CashApproval');
const PurchaseOrder = require('../models/procurement/PurchaseOrder');
const GoodsReceive = require('../models/procurement/GoodsReceive');
const FinanceHelper = require('./financeHelper');
const { getBillPayState, getPoAdvancePayState } = require('./apBillPayState');
const { vendorAdvancesLinkedToPurchaseOrderFilter } = require('./fullAdvancePoGate');

const round2 = (n) => Math.round((Number(n) || 0) * 100) / 100;
const userName = (u) => (u && typeof u === 'object'
  ? [u.firstName, u.lastName].filter(Boolean).join(' ').trim() || u.name || u.email || ''
  : '');
const isId = (id) => mongoose.Types.ObjectId.isValid(String(id || ''));
const METHOD_LABEL = {
  cash: 'Cash', check: 'Cheque', cheque: 'Cheque', bank_transfer: 'Bank transfer', bank: 'Bank transfer',
  credit_card: 'Credit card', ach: 'ACH', other: 'Other', Cash: 'Cash', Cheque: 'Cheque', 'Bank Transfer': 'Bank transfer'
};
const methodLabel = (m) => METHOD_LABEL[m] || (m ? String(m).replace(/_/g, ' ') : '');
const PAYMENT_STATUS = { pending_authority: 'In approval', fully_approved: 'Posted', rejected: 'Rejected', immediate: 'Posted' };
const accountLabel = (a) => (a && typeof a === 'object'
  ? [a.accountNumber || a.accountCode, a.name].filter(Boolean).join(' ')
  : '');

const JE_POPULATE = [
  { path: 'lines.account', select: 'accountNumber accountCode name type category' },
  { path: 'createdBy', select: 'firstName lastName email' },
  { path: 'postedBy', select: 'firstName lastName email' },
  { path: 'companyId', select: 'name' }
];

const shapeJournal = (je) => (je ? {
  id: je._id,
  number: je.entryNumber,
  date: je.date,
  status: je.status,
  description: je.description || '',
  reference: je.reference || '',
  company: je.companyId?.name || '',
  createdBy: userName(je.createdBy),
  createdAt: je.createdAt,
  postedBy: userName(je.postedBy),
  postedAt: je.postedDate || null,
  isAutoGenerated: Boolean(je.isAutoGenerated),
  lines: (je.lines || []).map((l) => ({
    account: accountLabel(l.account) || l.description || '—',
    accountCode: (l.account && (l.account.accountNumber || l.account.accountCode)) || '',
    accountName: (l.account && l.account.name) || l.description || '—',
    description: l.description || '',
    debit: round2(l.debit),
    credit: round2(l.credit)
  })),
  totalDebit: round2((je.lines || []).reduce((t, l) => t + (Number(l.debit) || 0), 0)),
  totalCredit: round2((je.lines || []).reduce((t, l) => t + (Number(l.credit) || 0), 0))
} : null);

const loadJournals = async (ids) => {
  const valid = [...new Set((ids || []).filter(isId).map(String))];
  if (!valid.length) return [];
  const jes = await JournalEntry.find({ _id: { $in: valid }, status: { $nin: ['cancelled'] } })
    .populate(JE_POPULATE).sort({ date: 1, createdAt: 1 }).lean();
  return jes.map(shapeJournal);
};

