const billDocument = async (id) => {
  const bill = await AccountsPayable.findById(id)
    .populate('companyId', 'name')
    .populate('createdBy', 'firstName lastName email')
    .populate('approvedBy', 'firstName lastName email')
    .populate('payeeEmployee', 'firstName lastName employeeId')
    .lean({ getters: true });
  if (!bill) return null;

  const apps = await ApPaymentApplication.find({
    $or: [{ accountsPayableId: bill._id }, { 'bills.billId': bill._id }],
    workflowStatus: { $ne: 'rejected' }
  }).populate('paymentMeta.bankAccountId', 'accountNumber accountCode name').sort({ createdAt: 1 }).lean();

  const amountForBill = (app) => {
    const line = (app.bills || []).find((b) => String(b.billId) === String(bill._id));
    return round2(line ? line.amount : app.amount);
  };
  const payments = apps.map((app) => ({
    journalEntryId: app.journalEntryId,
    date: app.finalizedAt || app.createdAt,
    kind: app.sourceType === 'bank_payment' ? 'Payment' : 'Advance adjusted',
    method: app.sourceType === 'bank_payment' ? methodLabel(app.paymentMeta?.paymentMethod) : (app.sourceType === 'cash_approval' ? 'Cash approval advance' : 'Vendor advance'),
    bank: accountLabel(app.paymentMeta?.bankAccountId),
    reference: app.paymentMeta?.reference || '',
    amount: amountForBill(app),
    status: PAYMENT_STATUS[app.workflowStatus] || app.workflowStatus
  }));
  // Older payments posted straight on the bill (journal linked on the payment line)
  const hasFinalizedBankApps = apps.some((a) => a.sourceType === 'bank_payment' && a.workflowStatus === 'fully_approved');
  (bill.payments || []).forEach((p) => {
    if (!p.journalEntry && hasFinalizedBankApps) return;
    if (p.journalEntry && payments.some((x) => String(x.journalEntryId) === String(p.journalEntry))) return;
    payments.push({
      journalEntryId: p.journalEntry || null,
      date: p.paymentDate,
      kind: 'Payment',
      method: methodLabel(p.paymentMethod),
      bank: '',
      reference: p.reference || '',
      amount: round2(p.amount),
      status: 'Posted'
    });
  });

  const payState = getBillPayState(bill);
  const payable = payState.payable;
  const paid = payState.settled;
  const balance = payState.balance;
  const inApproval = round2(Math.max(payState.pending, payments.filter((p) => p.status === 'In approval').reduce((t, p) => t + p.amount, 0)));

  const billJes = await JournalEntry.find({ referenceId: bill._id, referenceType: 'bill' }).select('_id').lean();
  const billJeIds = new Set(billJes.map((j) => String(j._id)));
  const journals = (await loadJournals([...billJes.map((j) => j._id), ...payments.map((p) => p.journalEntryId)]))
    .map((j) => ({ ...j, role: billJeIds.has(String(j.id)) ? 'Bill posting' : 'Payment' }));

  // Source documents for the trail
  const poIds = new Set();
  const grnIds = new Set();
  if (bill.referenceType === 'purchase_order' && bill.referenceId) poIds.add(String(bill.referenceId));
  if (bill.referenceType === 'grn' && bill.referenceId) grnIds.add(String(bill.referenceId));
  (bill.linkedGRNs || []).forEach((g) => { if (g.grnId) grnIds.add(String(g.grnId)); if (g.poId) poIds.add(String(g.poId)); });
  const grns = grnIds.size ? await GoodsReceive.find({ _id: { $in: [...grnIds].filter(isId) } }).select('receiveNumber grnNumber purchaseOrder').lean() : [];
  grns.forEach((g) => { if (g.purchaseOrder) poIds.add(String(g.purchaseOrder)); });
  const pos = poIds.size ? await PurchaseOrder.find({ _id: { $in: [...poIds].filter(isId) } }).select('orderNumber').lean() : [];

  const action = payState.canPay ? 'pay_bill' : null;

  const lineItems = (bill.lineItems || []).map((l) => {
    const amount = round2((Number(l.quantity) || 0) * (Number(l.unitPrice) || 0));
    return {
      description: [l.itemName, l.description].filter(Boolean).filter((v, i, a) => a.indexOf(v) === i).join(' — ') || '—',
      quantity: l.quantity,
      rate: round2(l.unitPrice),
      taxRate: l.taxRate || 0,
      amount
    };
  });

  return {
    kind: 'bill',
    kindLabel: bill.isAdvanceBill ? 'Advance bill' : 'Vendor bill',
    id: bill._id,
    number: bill.billNumber,
    status: bill.status,
    party: bill.vendor?.name || userName(bill.payeeEmployee) || '—',
    fields: [
      { label: 'Vendor', value: bill.vendor?.name || '—' },
      { label: 'Bill date', value: bill.billDate, type: 'date' },
      { label: 'Due date', value: bill.dueDate, type: 'date' },
      { label: 'Vendor invoice', value: bill.vendorInvoiceNumber || '—' },
      { label: 'Company', value: bill.companyId?.name || bill.company || '—' },
      { label: 'Project', value: bill.project || '—' },
      { label: 'Payment terms', value: String(bill.paymentTerms || '—').replace(/_/g, ' ') },
      { label: 'Created by', value: [userName(bill.createdBy), bill.createdAt ? { date: bill.createdAt } : null].filter(Boolean), type: 'user' },
      ...(bill.approvedBy ? [{ label: 'Approved by', value: [userName(bill.approvedBy), bill.approvedAt ? { date: bill.approvedAt } : null].filter(Boolean), type: 'user' }] : [])
    ],
    links: [
      ...pos.map((p) => ({ type: 'PO', number: p.orderNumber })),
      ...grns.map((g) => ({ type: 'GRN', number: g.receiveNumber || g.grnNumber }))
    ],
    lineColumns: ['Description', 'Qty', 'Rate', 'Tax %', 'Amount'],
    lines: lineItems,
    totals: [
      { label: 'Subtotal', amount: round2(bill.subtotal) },
      ...(Number(bill.taxAmount) ? [{ label: 'Tax', amount: round2(bill.taxAmount) }] : []),
      ...(Number(bill.discountAmount) ? [{ label: 'Discount', amount: -round2(bill.discountAmount) }] : []),
      ...(payable !== round2(bill.totalAmount) ? [{ label: 'Bill total', amount: round2(bill.totalAmount) }, { label: 'Payable (incl. late payment)', amount: payable }] : [{ label: 'Bill total', amount: payable, bold: true }]),
      ...(Number(bill.advanceApplied) ? [{ label: 'Advances adjusted', amount: -round2(bill.advanceApplied) }] : []),
      ...(Number(bill.amountPaid) ? [{ label: 'Paid', amount: -round2(bill.amountPaid) }] : []),
      ...(inApproval ? [{ label: 'In payment approval', amount: inApproval, muted: true }] : [])
    ],
    amount: payable,
    paid,
    balance,
    inApprovalAmount: inApproval,
    notes: bill.notes || '',
    payments: payments.sort((a, b) => new Date(a.date || 0) - new Date(b.date || 0)),
    journals,
    action,
    actionDisabledReason: payState.reason,
    printUrl: `/finance/bill-print/${bill._id}`,
    companyId: bill.companyId?._id || bill.companyId || null,
    vendorId: bill.vendor?.vendorId || null
  };
};

const cashApprovalDocument = async (id) => {
  const ca = await CashApproval.findById(id)
    .populate('vendor', 'name')
    .populate('companyId', 'name')
    .populate('createdBy', 'firstName lastName email')
    .populate('advanceIssuedBy', 'firstName lastName email')
    .populate('advanceBankAccount', 'accountNumber accountCode name')
    .lean();
  if (!ca) return null;

  const amount = round2(Number(ca.advanceAmount) || Number(ca.totalAmount) || 0);
  const issued = ['Advance Issued', 'Evidence Submitted', 'Payment Settled', 'Completed'].includes(ca.status);
  const settling = ca.status === 'Pending Finance' && ca.advanceIssuedAt && ca.evidenceSubmittedAt;
  const paid = issued || settling ? amount : 0;
  const financeOpen = ['Pending Finance', 'Finance Authority Approved'].includes(ca.status);
  const voucherAwaitingAuthorities = ca.status === 'Pending Finance' && ca.voucherEntryId && !settling;

  const caJes = await JournalEntry.find({ referenceId: ca._id }).select('_id').lean();
  const journals = (await loadJournals([ca.voucherEntryId, ...caJes.map((j) => j._id)])).map((j) => ({ ...j, role: 'Payment' }));
  const payments = journals.map((j) => ({
    journalEntryId: j.id,
    date: j.date,
    kind: 'Payment',
    method: methodLabel(ca.advancePaymentMethod),
    bank: accountLabel(ca.advanceBankAccount),
    reference: ca.advanceVoucherNo || '',
    amount: round2(j.totalCredit),
    status: j.status === 'posted' ? 'Posted' : 'In approval'
  }));

  const action = financeOpen ? 'cash_approval' : null;
  return {
    kind: 'cash-approval',
    kindLabel: 'Cash approval',
    id: ca._id,
    number: ca.caNumber,
    status: ca.status,
    party: ca.advanceToName || ca.vendor?.name || ca.requestingDepartment || '—',
    fields: [
      { label: 'Payee', value: ca.advanceToName || ca.vendor?.name || '—' },
      { label: 'Vendor', value: ca.vendor?.name || '—' },
      { label: 'Department', value: ca.requestingDepartment || '—' },
      { label: 'Approval date', value: ca.approvalDate, type: 'date' },
      { label: 'Company', value: ca.companyId?.name || '—' },
      { label: 'Purpose', value: ca.purpose || '—' },
      { label: 'Created by', value: [userName(ca.createdBy), ca.createdAt ? { date: ca.createdAt } : null].filter(Boolean), type: 'user' },
      ...(ca.advanceIssuedBy ? [{ label: 'Advance issued by', value: [userName(ca.advanceIssuedBy), ca.advanceIssuedAt ? { date: ca.advanceIssuedAt } : null].filter(Boolean), type: 'user' }] : [])
    ],
    links: [],
    lineColumns: ['Description', 'Qty', 'Rate', 'Tax %', 'Amount'],
    lines: (ca.items || []).map((l) => ({
      description: [l.itemName, l.description].filter(Boolean).filter((v, i, a) => a.indexOf(v) === i).join(' — ') || '—',
      quantity: l.quantity,
      rate: round2(l.unitPrice),
      taxRate: l.taxRate || 0,
      amount: round2(l.amount)
    })),
    totals: [
      { label: 'Subtotal', amount: round2(ca.subtotal) },
      ...(Number(ca.taxAmount) ? [{ label: 'Tax', amount: round2(ca.taxAmount) }] : []),
      ...(Number(ca.discountAmount) ? [{ label: 'Discount', amount: -round2(ca.discountAmount) }] : []),
      { label: 'Total', amount: round2(ca.totalAmount), bold: true },
      ...(Number(ca.advanceAmount) && round2(ca.advanceAmount) !== round2(ca.totalAmount) ? [{ label: 'Advance amount', amount: round2(ca.advanceAmount) }] : []),
      ...(paid ? [{ label: 'Paid', amount: -paid }] : []),
      ...(Number(ca.actualAmountSpent) ? [{ label: 'Actual spent', amount: round2(ca.actualAmountSpent), muted: true }] : []),
      ...(Number(ca.excessReturned) ? [{ label: 'Excess returned', amount: round2(ca.excessReturned), muted: true }] : [])
    ],
    amount,
    paid,
    balance: round2(amount - paid),
    inApprovalAmount: voucherAwaitingAuthorities ? amount : 0,
    notes: ca.advanceRemarks || '',
    payments,
    journals,
    action,
    actionLabel: settling ? 'Settle payment' : ca.status === 'Finance Authority Approved' ? 'Post payment' : !ca.voucherEntryId ? 'Create payment voucher' : 'Approve payment',
    actionDisabledReason: action ? '' : issued ? 'Paid' : `Not at Finance yet (${ca.status})`,
    printUrl: `/procurement/cash-approvals/${ca._id}/print`,
    companyId: ca.companyId?._id || ca.companyId || null,
    vendorId: ca.vendor?._id || null
  };
};

const poDocument = async (id) => {
  const po = await PurchaseOrder.findById(id)
    .populate('vendor', 'name')
    .populate('companyId', 'name')
    .populate('createdBy', 'firstName lastName email')
    .lean();
  if (!po) return null;

  const advances = await VendorAdvance.find(vendorAdvancesLinkedToPurchaseOrderFilter(po._id))
    .populate('bankAccountId', 'accountNumber accountCode name')
    .sort({ paymentDate: 1 }).lean();
  const payments = advances.map((a) => ({
    journalEntryId: a.journalEntryId,
    date: a.paymentDate || a.createdAt,
    kind: 'Advance',
    method: methodLabel(a.paymentMethod),
    bank: accountLabel(a.bankAccountId),
    reference: a.reference || a.chequeNumber || '',
    amount: round2(a.amount),
    status: PAYMENT_STATUS[a.voucherWorkflowStatus] || 'Posted'
  }));
  // Same rule as the Vendor Advance PO queue
  const payState = getPoAdvancePayState(po, advances);
  const posted = payState.paid;
  const inApproval = payState.pending;
  const total = payState.total;
  const balance = round2(total - posted);
  const payingIds = new Set(advances.map((a) => String(a.payingJournalEntryId || '')));
  const journals = (await loadJournals(advances.flatMap((a) => [a.journalEntryId, a.payingJournalEntryId])))
    .map((j) => ({ ...j, role: payingIds.has(String(j.id)) ? 'Advance — paying company' : 'Advance payment' }));
  const action = payState.canPay ? 'po_advance' : null;

  return {
    kind: 'po',
    kindLabel: 'PO advance',
    id: po._id,
    number: po.orderNumber,
    status: po.status,
    party: po.vendor?.name || '—',
    fields: [
      { label: 'Vendor', value: po.vendor?.name || '—' },
      { label: 'Order date', value: po.orderDate, type: 'date' },
      { label: 'Expected delivery', value: po.expectedDeliveryDate, type: 'date' },
      { label: 'Payment terms', value: po.paymentTerms || '—' },
      { label: 'Company', value: po.companyId?.name || '—' },
      { label: 'Created by', value: [userName(po.createdBy), po.createdAt ? { date: po.createdAt } : null].filter(Boolean), type: 'user' }
    ],
    links: [],
    lineColumns: ['Description', 'Qty', 'Rate', 'Tax %', 'Amount'],
    lines: (po.items || []).map((l) => ({
      description: [l.description, l.specification].filter(Boolean).join(' — ') || '—',
      quantity: l.quantity,
      rate: round2(l.unitPrice),
      taxRate: l.taxRate || 0,
      amount: round2(l.amount)
    })),
    totals: [
      { label: 'Subtotal', amount: round2(po.subtotal) },
      ...(Number(po.taxAmount) ? [{ label: 'Tax', amount: round2(po.taxAmount) }] : []),
      ...(Number(po.shippingCost) ? [{ label: 'Shipping', amount: round2(po.shippingCost) }] : []),
      ...(Number(po.orderDiscount) ? [{ label: 'Discount', amount: -round2(po.orderDiscount) }] : []),
      { label: 'PO total', amount: total, bold: true },
      ...(posted ? [{ label: 'Advance paid', amount: -posted }] : []),
      ...(inApproval ? [{ label: 'In payment approval', amount: inApproval, muted: true }] : [])
    ],
    amount: total,
    paid: posted,
    balance,
    inApprovalAmount: inApproval,
    notes: po.notes || '',
    payments,
    journals,
    action,
    actionLabel: 'Pay advance',
    actionDisabledReason: payState.reason,
    printUrl: null,
    companyId: po.companyId?._id || po.companyId || null,
    vendorId: po.vendor?._id || null,
    po: { _id: po._id, orderNumber: po.orderNumber, totalAmount: po.totalAmount }
  };
};

const buildPayableDocument = async (kind, id) => {
  if (!isId(id)) return null;
  if (kind === 'bill') return billDocument(id);
  if (kind === 'cash-approval') return cashApprovalDocument(id);
  if (kind === 'po') return poDocument(id);
  return null;
};

