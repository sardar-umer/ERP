const buildPaymentDetail = async (journalEntryId) => {
  if (!isId(journalEntryId)) return null;
  const jeDoc = await JournalEntry.findById(journalEntryId).populate(JE_POPULATE).populate('companyId', 'name').lean();
  if (!jeDoc) return null;

  const [app, advance, ca, legacyBill] = await Promise.all([
    ApPaymentApplication.findOne({ $or: [{ journalEntryId: jeDoc._id }, { payingJournalEntryId: jeDoc._id }] })
      .populate('paymentMeta.bankAccountId', 'accountNumber accountCode name')
      .populate('createdBy', 'firstName lastName email')
      .populate('financeAuthorityApprovals.approver', 'firstName lastName email')
      .lean(),
    VendorAdvance.findOne({ $or: [{ journalEntryId: jeDoc._id }, { payingJournalEntryId: jeDoc._id }] })
      .populate('bankAccountId', 'accountNumber accountCode name')
      .populate('createdBy', 'firstName lastName email')
      .lean(),
    CashApproval.findOne({ $or: [{ voucherEntryId: jeDoc._id }, { _id: jeDoc.referenceId || null }] })
      .populate('vendor', 'name').populate('advanceBankAccount', 'accountNumber accountCode name')
      .lean(),
    AccountsPayable.findOne({ 'payments.journalEntry': jeDoc._id }).select('billNumber vendor vendorInvoiceNumber billDate payments').lean()
  ]);

  const docs = [];
  let payee = '';
  let method = '';
  let bank = '';
  let reference = '';
  let status = jeDoc.status === 'posted' ? 'Posted' : jeDoc.status === 'draft' ? 'Draft' : jeDoc.status;
  let createdBy = userName(jeDoc.createdBy);
  let approvals = [];
  let advanceAdjusted = 0;
  let kindLabel = 'Payment';

  if (app) {
    const lines = (app.bills || []).length ? app.bills : [{ billId: app.accountsPayableId, billNumber: app.billNumber, amount: app.amount }];
    const bills = await AccountsPayable.find({ _id: { $in: lines.map((l) => l.billId).filter(isId) } })
      .select('billNumber vendor vendorInvoiceNumber billDate').lean();
    const byId = new Map(bills.map((b) => [String(b._id), b]));
    lines.forEach((l) => {
      const b = byId.get(String(l.billId)) || {};
      docs.push({ type: 'Bill', kind: 'bill', id: l.billId, number: b.billNumber || l.billNumber, reference: b.vendorInvoiceNumber || '', date: b.billDate, amount: round2(l.amount) });
    });
    payee = bills[0]?.vendor?.name || '';
    if (app.sourceType === 'bank_payment') {
      method = methodLabel(app.paymentMeta?.paymentMethod);
      bank = accountLabel(app.paymentMeta?.bankAccountId);
    } else {
      kindLabel = 'Advance adjustment';
      method = app.sourceType === 'cash_approval' ? 'Cash approval advance' : 'Vendor advance';
      advanceAdjusted = round2(app.amount);
    }
    reference = app.paymentMeta?.reference || '';
    status = PAYMENT_STATUS[app.workflowStatus] || status;
    createdBy = userName(app.createdBy) || createdBy;
    approvals = (app.financeAuthorityApprovals || []).map((a) => ({
      label: a.authorityLabel || a.authorityKey, by: userName(a.approver), at: a.approvedAt, decision: a.decision
    }));
  } else if (advance) {
    kindLabel = 'Vendor advance';
    payee = advance.vendor?.name || '';
    method = methodLabel(advance.paymentMethod);
    bank = accountLabel(advance.bankAccountId);
    reference = advance.reference || advance.chequeNumber || '';
    status = PAYMENT_STATUS[advance.voucherWorkflowStatus] || status;
    createdBy = userName(advance.createdBy) || createdBy;
    if (advance.referenceId) {
      const po = await PurchaseOrder.findById(advance.referenceId).select('orderNumber orderDate').lean();
      if (po) docs.push({ type: 'PO', kind: 'po', id: po._id, number: po.orderNumber, reference: '', date: po.orderDate, amount: round2(advance.amount) });
    }
    (advance.allocations || []).forEach((al) => docs.push({ type: 'Bill', kind: 'bill', id: al.billId, number: al.billNumber, reference: 'Advance adjusted', date: al.appliedAt, amount: round2(al.amount) }));
  } else if (ca) {
    kindLabel = 'Cash approval payment';
    payee = ca.advanceToName || ca.vendor?.name || '';
    method = methodLabel(ca.advancePaymentMethod);
    bank = accountLabel(ca.advanceBankAccount);
    reference = ca.advanceVoucherNo || '';
    docs.push({ type: 'Cash approval', kind: 'cash-approval', id: ca._id, number: ca.caNumber, reference: ca.purpose || '', date: ca.approvalDate, amount: round2(Number(ca.advanceAmount) || Number(ca.totalAmount) || 0) });
  } else if (legacyBill) {
    const p = (legacyBill.payments || []).find((x) => String(x.journalEntry) === String(jeDoc._id));
    payee = legacyBill.vendor?.name || '';
    method = methodLabel(p?.paymentMethod);
    reference = p?.reference || '';
    docs.push({ type: 'Bill', kind: 'bill', id: legacyBill._id, number: legacyBill.billNumber, reference: legacyBill.vendorInvoiceNumber || '', date: legacyBill.billDate, amount: round2(p?.amount) });
  }

  const payingJeId = String(app?.payingJournalEntryId || advance?.payingJournalEntryId || '');
  const journals = (await loadJournals([jeDoc._id, app?.journalEntryId, app?.payingJournalEntryId, advance?.journalEntryId, advance?.payingJournalEntryId]))
    .map((j) => ({ ...j, role: payingJeId && String(j.id) === payingJeId ? 'Paying company' : (payingJeId ? 'Bill company' : 'Payment') }));
  // Summary from the ledger lines so it always matches the accounting entry
  const main = journals.find((j) => String(j.id) === String(jeDoc._id)) || journals[0];
  const bankAccountName = bank;
  const wht = round2((main?.lines || []).filter((l) => l.credit && WHT_RX.test(l.account)).reduce((t, l) => t + l.credit, 0));
  const applied = round2(docs.reduce((t, d) => t + (d.reference === 'Advance adjusted' ? 0 : d.amount), 0)) || round2(main?.totalDebit);
  const fromBank = advanceAdjusted ? 0 : round2(applied - wht);

  return {
    id: jeDoc._id,
    number: jeDoc.entryNumber,
    kindLabel,
    status,
    date: jeDoc.date,
    payee: payee || '—',
    company: jeDoc.companyId?.name || '',
    fields: [
      { label: 'Payee', value: payee || '—' },
      { label: 'Date', value: jeDoc.date, type: 'date' },
      { label: 'Paid by', value: method || '—' },
      { label: 'Bank', value: bankAccountName || '—' },
      { label: 'Reference', value: reference || '—' },
      { label: 'Company', value: jeDoc.companyId?.name || '—' },
      { label: 'Prepared by', value: [createdBy, jeDoc.createdAt ? { date: jeDoc.createdAt } : null].filter(Boolean), type: 'user' },
      ...(jeDoc.postedBy ? [{ label: 'Posted by', value: [userName(jeDoc.postedBy), jeDoc.postedDate ? { date: jeDoc.postedDate } : null].filter(Boolean), type: 'user' }] : [])
    ],
    documents: docs,
    summary: [
      { label: advanceAdjusted ? 'Adjusted against bills' : 'Applied to documents', amount: advanceAdjusted || applied },
      ...(advanceAdjusted ? [] : [
        { label: 'Income tax withheld', amount: wht },
        { label: 'Paid from bank', amount: fromBank }
      ]),
      { label: 'Settled with payee', amount: advanceAdjusted || applied, bold: true }
    ],
    approvals,
    journals,
    voucherUrl: `/finance/vouchers/${jeDoc._id}`
  };
};

module.exports = { buildPayableDocument, buildPaymentDetail };
